// =========================================================
// LANGUAGE FUNCTIONS
// =========================================================

function applyLanguage(language) {
    const selectedLanguage = translations[language] || translations.en;

    // Translate normal text and select options
    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.getAttribute("data-i18n");

        if (selectedLanguage[key]) {
            element.textContent = selectedLanguage[key];
        }
    });

    // Translate input placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        const key = element.getAttribute("data-i18n-placeholder");

        if (selectedLanguage[key]) {
            element.placeholder = selectedLanguage[key];
        }
    });

    localStorage.setItem("welfareconnect-language", language);

    document.documentElement.lang = language;
}


function changeLanguage(language) {
    applyLanguage(language);
}


// =========================================================
// LOAD SAVED LANGUAGE
// =========================================================

document.addEventListener("DOMContentLoaded", () => {
    const savedLanguage =
        localStorage.getItem("welfareconnect-language") || "en";

    applyLanguage(savedLanguage);

    const selector = document.getElementById("language-selector");

    if (selector) {
        selector.value = savedLanguage;

        selector.addEventListener("change", function () {
            changeLanguage(this.value);
        });
    }
});